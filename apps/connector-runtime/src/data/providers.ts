export function generateHealth(providerId: string): ConnectorHealth {
  const base: Record<string, Partial<ConnectorHealth>> = {
    'aws-prod':        { apiLatencyMs: 42, healthScore: 97, apiVersion: 'AWS SDK v3.600' },
    'azure-prod':      { apiLatencyMs: 67, healthScore: 91, apiVersion: 'Azure SDK 2024-01' },
    'gcp-prod':        { apiLatencyMs: 55, healthScore: 94, apiVersion: 'GCP API v1' },
    'k8s-eks-prod':    { apiLatencyMs: 18, healthScore: 99, apiVersion: 'k8s v1.29.3' },
    'github-org':      { apiLatencyMs: 87, healthScore: 88, apiVersion: 'GitHub REST v2022-11-28' },
    'terraform-cloud': { apiLatencyMs: 123, healthScore: 82, apiVersion: 'TFC API v2' },
    'cloudflare-main': { apiLatencyMs: 31, healthScore: 96, apiVersion: 'CF API v4' },
    'docker-registry': { apiLatencyMs: 24, healthScore: 93, apiVersion: 'OCI Registry API v2' },
  };

  const b = base[providerId] || {};
  return {
    providerId,
    apiLatencyMs: b.apiLatencyMs ?? 50,
    lastSyncDurationMs: (b.apiLatencyMs ?? 50) * 240,
    totalResources: resourceCounts[providerId] ?? 0,
    errorCount: 0,
    rateLimitUsage: Math.floor(Math.random() * 30),
    credentialStatus: 'valid',
    apiVersion: b.apiVersion ?? 'v1',
    webhookConnected: true,
    retryCount: 0,
    healthScore: b.healthScore ?? 90,
    lastSyncAt: new Date().toISOString(),
  };
}
